const silhouette = (Wp: number, phone = false) => {
  const out = new Float32Array(Math.ceil(Wp) + 1);
  driftSilhouette(out, 0, Wp, phone);
  return out;
};

/** Значение ломаной [x, y, …] в x (линейно между узлами). */
function lineAt(nodes: readonly number[], x: number): number {
  for (let i = 2; i < nodes.length; i += 2) {
    const xa = nodes[i - 2]!;
    const xb = nodes[i]!;
    if (x <= xb) return nodes[i - 1]! + ((nodes[i + 1]! - nodes[i - 1]!) * (x - xa)) / (xb - xa);
  }
  return nodes[nodes.length - 1]!;
}

describe('snow drift silhouette', () => {
  it('desktop silhouette is unchanged', () => {
    for (const [w, gold] of Object.entries(GOLD)) {
      const s = silhouette(Number(w));
      const err = Math.max(...gold.map((v, i) => Math.abs(s[i * 7]! - v)));
      expect(err, `Wp ${w}`).toBeLessThan(1e-6);
    }
  });

  it('phone at 360 (strip 1872 px of pattern) is the whole reference picture', () => {
    // на 1366 десктоп показывает ровно середину эталона [253, 1619]; телефон — её же плюс края картинки
    const phone = silhouette(1872, true);
    const desk = silhouette(1366);
    let mid = 0;
    for (let x = 1; x <= 1365; x++) mid = Math.max(mid, Math.abs(phone[x + 253]! - desk[x]!));
    expect(mid).toBeLessThan(1e-6);
    let edges = 0;
    for (let x = 0; x <= 253; x++) {
      edges = Math.max(edges, Math.abs(phone[x]! - lineAt(DRIFT_EDGE_L, x)));
      edges = Math.max(edges, Math.abs(phone[1619 + x]! - lineAt(DRIFT_EDGE_R, x)));
    }
    expect(edges).toBeLessThan(1e-4);
  });

  it('reference edges join the parts without steps', () => {
    expect(Math.abs(lineAt(DRIFT_L, 0) - lineAt(DRIFT_EDGE_L, DRIFT_PHONE.edge))).toBeLessThan(0.3);
    expect(Math.abs(lineAt(DRIFT_R, 291) - lineAt(DRIFT_EDGE_R, 0))).toBeLessThan(0.3);
    expect(DRIFT_EDGE_L[DRIFT_EDGE_L.length - 2]).toBe(DRIFT_PHONE.edge);
    expect(DRIFT_EDGE_R[DRIFT_EDGE_R.length - 2]).toBe(DRIFT_PHONE.edge);
  });
});

describe('drift geometry', () => {
  const o = SNOW_DRIFT_DEFAULTS;

  it('recognises the phone by the canvas height set in CSS', () => {
    // телефон: холст 98 px узора × --snow-k 0,1795 (globals.css)
    const phone = geometry(336, DRIFT_PHONE.band * DRIFT_PHONE.k, 672, 35, o);
    expect(phone.phone).toBe(true);
    expect(phone.k).toBeCloseTo(DRIFT_PHONE.k, 10);
    expect(phone.Wp).toBeCloseTo(336 / DRIFT_PHONE.k, 6);
    // от 768: холст 46 px при --snow-k 1
    const desk = geometry(1318, 46, 2636, 92, o);
    expect(desk.phone).toBe(false);
    expect(desk.k).toBe(1);
  });

  it('caps the canvas density at 3 on the phone and at 2 on the wide strip', () => {
    // телефон: холст маленький (336 × 17,6 css на 360), при 2× фактура снега мягче макета
    expect(o.maxDprCompact).toBe(3);
    expect(o.maxDpr).toBe(2);
  });

  it('documents that the intermediate scale 0.5 is not compatible with the phone profile', () => {
    // холст 46 × 0,5 = 23 px тоже «телефон», но масштаб тогда 23/98, а не 0,5
    const g = geometry(336, 23, 336, 23, o);
    expect(g.phone).toBe(true);
    expect(g.k).toBeCloseTo(23 / 98, 10);
  });
});
